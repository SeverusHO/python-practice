#The // operator is the floor division operator. It performs integer division and returns the largest integer less than or equal to the result of the division. In this case, 9 divided by 2 is 4.5, but the floor division operator will return 4, which is the largest integer less than or equal to 4.5.
print (9//2) 
#The % operator is the modulus operator. It returns the remainder of the division  valuable in determining if a number is even or odd.
